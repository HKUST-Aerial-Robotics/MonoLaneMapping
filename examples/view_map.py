"""Export a MonoLaM map as a self-contained, interactive 3D HTML file."""

import argparse
from pathlib import Path

import numpy as np
import plotly.graph_objects as go
from plotly.colors import qualitative


def export_map(map_file, output_file):
    # map.npy is generated locally by LaneUI.save_map and contains Python objects.
    lanes = np.load(map_file, allow_pickle=True).item()['lanes_in_map']
    if not lanes:
        raise ValueError(f'{map_file}: no lanes to display')

    origin = np.asarray(next(iter(lanes.values()))['xyz'][0, :3])
    figure = go.Figure()
    for index, (lane_id, lane) in enumerate(lanes.items()):
        color = qualitative.Plotly[index % len(qualitative.Plotly)]
        label = f"Lane {lane_id} · category {lane['category']}"
        x, y, z = (lane['xyz'][:, :3] - origin).T
        figure.add_trace(go.Scatter3d(
            x=x, y=y, z=z, name=label, mode='lines',
            line={'color': color, 'width': 5},
        ))
    controls = np.concatenate([lane['ctrl_pts'] for lane in lanes.values()]) - origin
    raw_points = np.concatenate([lane['xyz_raw'][:, :3] for lane in lanes.values()]) - origin
    figure.add_trace(go.Scatter3d(
        x=controls[:, 0], y=controls[:, 1], z=controls[:, 2],
        name='Control points', mode='markers',
        marker={'color': '#d62728', 'size': 4}, visible='legendonly',
    ))
    figure.add_trace(go.Scatter3d(
        x=raw_points[:, 0], y=raw_points[:, 1], z=raw_points[:, 2],
        name='Raw detections', mode='markers',
        marker={'color': '#667085', 'size': 2, 'opacity': 0.45}, visible='legendonly',
    ))
    bounds = np.concatenate([controls, raw_points, *[lane['xyz'][:, :3] - origin for lane in lanes.values()]])
    center = (bounds.min(axis=0) + bounds.max(axis=0)) / 2
    span = np.maximum(np.ptp(bounds, axis=0), 1.0) * 1.12
    scene = {
        'aspectmode': 'manual',
        'aspectratio': dict(zip('xyz', 1.7 * span / span.max())),
        'camera': {'eye': {'x': 1.35, 'y': 0.45, 'z': 1.8}},
    }
    for axis, mid, width in zip('xyz', center, span):
        scene[f'{axis}axis'] = {'title': f'Local {axis.upper()} (m)', 'range': [mid - width / 2, mid + width / 2]}
    figure.update_layout(
        title='MonoLaM lane map',
        scene=scene,
        template='plotly_white', margin={'l': 0, 'r': 0, 't': 55, 'b': 0},
    )
    output_file.parent.mkdir(parents=True, exist_ok=True)
    figure.write_html(output_file, include_plotlyjs=True,
                      config={'displaylogo': False, 'showTips': False})
    return len(lanes)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('map_file', type=Path, help='Trusted map.npy generated by MonoLaM')
    parser.add_argument('output_file', type=Path, help='Path of the standalone HTML')
    args = parser.parse_args()
    lane_count = export_map(args.map_file, args.output_file)
    print(f'Exported {lane_count} lanes to {args.output_file}')
